#!/usr/bin/env bash
# Assembles tests.s, dropping the few forms GNU as can't re-encode, and writes the test
# table (tests.h) for rosetta_fuzz.c: code bytes, per-test offset and length.
set -euo pipefail
D="$1"
cd "$D"
cp tests.s tests.work.s
for round in 1 2 3 4 5; do
    if as --64 -o tests.o tests.work.s 2> as.err; then break; fi
    # comment out the failing lines (the instruction of a test; its label and ret stay)
    grep -o '^tests.work.s:[0-9]*' as.err | cut -d: -f2 | sort -un > bad.lines
    awk 'NR==FNR { bad[$1] = 1; next } (FNR in bad) { print "    # dropped: " $0; next } { print }' bad.lines tests.work.s > t.tmp
    mv t.tmp tests.work.s
done
as --64 -o tests.o tests.work.s
objcopy -O binary --only-section=.text tests.o tests.bin
nm -n tests.o | awk '$3 ~ /^t[0-9]+$/ { print $1, substr($3, 2) }' > tests.syms
python3 - <<'PY'
import struct
code = open('tests.bin', 'rb').read()
syms = sorted((int(a, 16), int(b)) for a, b in (l.split() for l in open('tests.syms')))
n = max(t for _, t in syms) + 1
off = [0] * n
for a, t in syms:
    off[t] = a
dropped = set()
for i, line in enumerate(open('tests.work.s')):
    pass
lines = open('tests.work.s').read().split('\n')
cur = None
for l in lines:
    if l.startswith('t') and l.endswith(':'):
        cur = int(l[1:-1])
    elif '# dropped' in l and cur is not None:
        dropped.add(cur)
with open('tests.h', 'w') as f:
    f.write('/* generated by build-tests.sh from the game\'s instruction forms */\n')
    f.write('#define NTESTS %d\n' % n)
    f.write('static const unsigned int test_off[NTESTS + 1] = {%s};\n' % ','.join(str(o) for o in off + [len(code)]))
    f.write('static const unsigned char test_dropped[NTESTS] = {%s};\n' % ','.join('1' if i in dropped else '0' for i in range(n)))
    f.write('static const unsigned char test_code[%d] = {\n' % len(code))
    for i in range(0, len(code), 32):
        f.write(','.join(str(b) for b in code[i:i + 32]) + ',\n')
    f.write('};\n')
forms = {}
for l in open('forms.tsv'):
    i, key, cnt, text, raw = l.rstrip('\n').split('\t')
    forms[int(i)] = (text.replace('\\', '\\\\').replace('"', '\\"'), int(cnt))
with open('forms.h', 'w') as f:
    f.write('static const char *const form_text[%d] = {\n' % n)
    for i in range(n):
        f.write('    "%s",\n' % forms[i][0])
    f.write('};\nstatic const unsigned int form_count[%d] = {%s};\n' % (n, ','.join(str(forms[i][1]) for i in range(n))))
print('tests', n, 'dropped', len(dropped), 'code bytes', len(code))
PY
